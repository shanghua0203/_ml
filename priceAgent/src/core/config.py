"""
================================================================================
系統設定與環境變數管理模組
================================================================================

本模組負責管理整個比價機器人的所有設定參數，包括：
1. Ollama LLM 模型的連線設定
2. Brave Search API 的金鑰設定
3. 搜尋與快取的行為設定
4. 資料庫路徑設定
5. 比價相關的價格門檻設定

使用說明：
- 所有設定透過 .env 檔案進行配置
- 程式碼中直接使用 'settings' 全域實例來存取設定值
- 可以呼叫 Settings.validate() 來驗證必要設定是否完備

================================================================================
"""

# ==============================================================================
# 引入必要的外部套件
# ==============================================================================

import os  # 用於存取系統環境變數
from pathlib import Path  # 用於處理跨平台的檔案路徑
from typing import Optional  # 用於類型提示，表示該變數可能為 None

from dotenv import load_dotenv  # 用於載入 .env 檔案中的環境變數

# ==============================================================================
# 載入環境變數
# ==============================================================================

# 載入專案根目錄下的 .env 檔案
# .env 檔案格式範例：
#   OLLAMA_BASE_URL=http://localhost:11434
#   OLLAMA_MODEL=gemma3:27b
#   BRAVE_API_KEY=your_api_key_here
#   SEARCH_RESULTS_COUNT=5
load_dotenv()

# ==============================================================================
# 設定類別定義
# ==============================================================================


class Settings:
    """
    專案設定類別 - 管理所有系統參數

    這個類別使用類別屬性（class variable）的方式來儲存設定，
    確保整個應用程式中只有一份設定實例（Singleton 模式）。

    屬性說明：
    ---------
    1. Ollama 設定區：
       - OLLAMA_BASE_URL: Ollama 服務的 URL 位置（預設為本地 11434 埠）
       - OLLAMA_MODEL: 使用的 LLM 模型名稱（預設為 gemma3:27b）

    2. Brave Search API 設定區：
       - BRAVE_API_KEY: Brave Search API 的認證金鑰（必要，None 表示未設定）

    3. 搜尋與快取設定區：
       - SEARCH_RESULTS_COUNT: 每次搜尋返回的結果筆數（預設 3 筆）
       - CACHE_EXPIRY_HOURS: 快取過期時間（預設 24 小時）

    4. 資料庫路徑設定區：
       - DATABASE_PATH: 購物紀錄資料庫的完整路徑
         預設為專案根目錄下的 data/shopping.db

    5. 比價機制設定區：
       - MIN_PRICE_THRESHOLD: 最低價格門檻（預設 100 元）
         低於此價格的商品會被標記為高風險
       - RISK_PRICE_MULTIPLIER: 風險價格倍數（預設 0.5）
         用於計算價格過低時的風險等級

    使用範例：
    ---------
    from src.core.config import settings

    # 取得設定值
    print(f"使用模型：{settings.OLLAMA_MODEL}")
    print(f"搜尋結果數：{settings.SEARCH_RESULTS_COUNT}")

    # 驗證設定
    errors = Settings.validate()
    if errors:
        print("設定錯誤：")
        for error in errors:
            print(f" - {error}")
    """

    # --------------------------------------------------------------------------
    # Ollama 設定區
    # --------------------------------------------------------------------------
    # 這些設定用於連線到本地端的 Ollama LLM 服務
    #
    # OLLAMA_BASE_URL: Ollama 服務的 Base URL
    #   格式：http://localhost:11434
    #   用途：所有 LLM 相關請求都會發送到這個位址
    #
    # OLLAMA_MODEL: 使用的模型名稱
    #   格式：model_name:tag
    #   用途：指定要使用哪個 LLM 模型進行分析
    #   常見模型：
    #     - gemma3:27b (預設)：Google 的高效能模型
    #     - llama3:8b：Meta 的高效能小模型
    #     - mistral:7b：Mistral 的高效能模型
    OLLAMA_BASE_URL: str = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")
    OLLAMA_MODEL: str = os.getenv("OLLAMA_MODEL", "gemma3:27b")

    # --------------------------------------------------------------------------
    # Brave Search API 設定區
    # --------------------------------------------------------------------------
    # 這些設定用於存取 Brave Search 搜尋引擎
    #
    # BRAVE_API_KEY: Brave Search API 的金鑰
    #   格式：字串 (從 https://brave.com/search/api/ 申請)
    #   用途：進行網際網路商品價格搜尋
    #   安全性：此金鑰應該保存在 .env 檔案中，不應提交到版本控制
    BRAVE_API_KEY: Optional[str] = os.getenv("BRAVE_API_KEY")

    # --------------------------------------------------------------------------
    # 搜尋與快取設定區
    # --------------------------------------------------------------------------
    # 這些設定控制搜尋行為與快取機制
    #
    # SEARCH_RESULTS_COUNT: 每次搜尋返回的結果筆數
    #   類型：整數
    #   用途：決定初始搜尋時要取得多少個商品候選
    #   建議值：3-10，數量越多代表越多商品參與比價，但處理時間較長
    SEARCH_RESULTS_COUNT: int = 7

    # CACHE_EXPIRY_HOURS: 快取過期時間（小時）
    #   類型：整數
    #   用途：設定搜尋結果快取的有效期限
    #   機制：超過此時間的快取會在下次存取時被清除
    #   建議值：24 小時（一天），確保價格資訊不會過舊
    CACHE_EXPIRY_HOURS: int = 24

    # --------------------------------------------------------------------------
    # 抓取Concurrency設定區
    # --------------------------------------------------------------------------
    # 這些設定控制網頁抓取的併發行為
    #
    # MAX_CONCURRENT_SCRAPES: 最大併發抓取數量
    #   類型：整數
    #   用途：控制同時進行網頁抓取的最大數量
    #   機制：使用 asyncio.Semaphore 限制併發數量
    #   建議值：3-5，數量越多抓取越快，但可能增加資源消耗與被擋風險
    MAX_CONCURRENT_SCRAPES: int = 3

    # --------------------------------------------------------------------------
    # 資料庫路徑設定區
    # --------------------------------------------------------------------------
    # 這些設定決定資料儲存位置
    #
    # DATABASE_PATH: 購物紀錄資料庫的完整路徑
    #   類型：Path 物件
    #   生成方式：自動根據本檔案位置推算
    #   結構：專案根目錄/data/shopping.db
    #   用途：儲存所有比價歷史與搜尋紀錄
    DATABASE_PATH: Path = Path(__file__).parent.parent.parent / "data" / "shopping.db"

    # --------------------------------------------------------------------------
    # 比價機制設定區
    # --------------------------------------------------------------------------
    # 這些設定控制價格風險判斷機制
    #
    # MIN_PRICE_THRESHOLD: 最低價格門檻（新台幣）
    #   類型：浮點數
    #   預設值：100 元
    #   用途：低於此價格的商品會被標記為高風險
    #   理由：極低價格通常是詐騙或誤標的跡象
    #
    # RISK_PRICE_MULTIPLIER: 風險價格倍數
    #   類型：浮點數
    #   預設值：0.5 (50%)
    #   用途：與最低門檻相乘計算風險等級
    #   計算：若最低門檻 100 元，倍數 0.5，則 50 元以下為高風險
    MIN_PRICE_THRESHOLD: float = 100  # 最低價格門檻（新台幣）
    RISK_PRICE_MULTIPLIER: float = 0.5  # 風險價格倍數（低於此值標記風險）

    # --------------------------------------------------------------------------
    # 類別方法
    # --------------------------------------------------------------------------

    @classmethod
    def validate(cls) -> list[str]:
        """
        驗證必要設定是否完成

        用途：
        ---------
        在程式啟動時檢查所有必要設定是否已經設定，
        如果有缺少，會返回錯誤訊息清單讓使用者修正。

        驗證項目：
        ---------
        1. BRAVE_API_KEY：比價功能必須的 API 金鑰

        返回值：
        ---------
        list[str]：錯誤訊息清單
          - [] 表示所有設定都正確
          - ["BRAVE_API_KEY 未設定..."] 表示有錯誤

        使用範例：
        ---------
        errors = Settings.validate()
        if errors:
            print("❌ 設定錯誤：")
            for error in errors:
                print(f"   - {error}")
            return 1  # 結束程式
        print("✅ 所有設定正確")
        """

        # 初始化錯誤訊息清單
        errors: list[str] = []

        # 檢查 Brave API 金鑰是否已設定
        # 沒有金鑰就無法進行網際網路搜尋，比價功能無法運作
        if not cls.BRAVE_API_KEY:
            errors.append("BRAVE_API_KEY 未設定，請在 .env 檔案中設定")

        # 返回所有錯誤訊息
        # 如果清單為空，表示所有設定都正確
        return errors


# ==============================================================================
# 全域實例
# ==============================================================================

# 建立 Settings 類別的全域實例
# 這是整個專案唯一的設定物件
# 所有模組都可以透過 'from src.core.config import settings' 來存取設定
settings = Settings()
